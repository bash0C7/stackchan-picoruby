require "fileutils"
require "open3"
require "rbs"
require "tmpdir"

# Generates RBS from the inline annotations with rbs-inline and renders it as Markdown API reference.
module ApiDocs
  ROOT = File.expand_path("..", __dir__)
  BEGIN_MARK = "<!-- BEGIN API (generated by `rake docs`; edit the source comments) -->"
  END_MARK = "<!-- END API -->"
  RBS_INLINE = File.join(ROOT, "vendor/docs-tool/bin/rbs-inline")

  AREAS = {
    "lib" => ["lib", "lib/**/*.rb"],
    "pc" => ["pc", "pc/**/*.rb"],
    "aot" => ["aot/kernels", "aot/kernels/*.rb"],
    "acceptance" => ["acceptance", "acceptance/**/*.rb"],
    "tools" => ["tools", "tools/**/*.rb"],
  }.freeze

  # One documentation unit: a gem or an area, with its sources, generated RBS dir and output file.
  Target = Struct.new(
    :name, #: String
    :base, #: String
    :glob, #: String
    :sig_dir, #: String
    :readme, #: String?
    :doc, #: String?
    keyword_init: true
  )

  # Returns a target per mrbgem and per area in AREAS.
  #: () -> Array[Target]
  def self.targets
    gems = Dir.chdir(ROOT) { Dir["mrbgems/*"].select { |d| File.directory?(d) }.sort }.map do |dir|
      Target.new(name: File.basename(dir), base: "#{dir}/mrblib", glob: "#{dir}/mrblib/**/*.rb",
                 sig_dir: "#{dir}/sig/generated", readme: "#{dir}/README.md")
    end
    areas = AREAS.map do |name, (base, glob)|
      Target.new(name: name, base: base, glob: glob, sig_dir: "sig/generated/#{name}", doc: "docs/api/#{name}.md")
    end
    gems + areas
  end

  # Returns the Ruby files of target, relative to the repository root.
  #: (Target target) -> Array[String]
  def self.sources(target)
    Dir.chdir(ROOT) { Dir[target.glob].reject { |f| f.split("/").include?("test") }.sort }
  end

  # Runs rbs-inline over the sources of target and writes RBS under out_root. Aborts when rbs-inline fails.
  #: (Target target, String out_root) -> void
  def self.generate_sig(target, out_root)
    files = sources(target)
    return if files.empty?
    dest = File.join(out_root, target.sig_dir)
    FileUtils.rm_rf(dest)
    out, status = Open3.capture2e(RBS_INLINE, "--opt-out", "--base=#{target.base}", "--output=#{dest}", *files, chdir: ROOT)
    abort "rbs-inline failed for #{target.name}:\n#{out}" unless status.success?
  end

  # Parses an RBS file and returns its declarations.
  #: (String path) -> Array[RBS::AST::Declarations::Base]
  def self.parse(path)
    RBS::Parser.parse_signature(RBS::Buffer.new(name: path, content: File.read(path)))[2]
  end

  # Returns the generated RBS files of target under out_root.
  #: (Target target, String out_root) -> Array[String]
  def self.sig_files(target, out_root)
    Dir[File.join(out_root, target.sig_dir, "**/*.rbs")].sort
  end

  # One documented member of a scope: kind, name, signatures, comment, visibility and source file.
  Member = Struct.new(
    :kind, #: Symbol
    :name, #: String
    :signatures, #: Array[String]
    :comment, #: String?
    :visibility, #: Symbol
    :source #: String
  )
  # One class or module with its superclass, comment, members and source files.
  Scope = Struct.new(
    :name, #: String
    :super_class, #: String?
    :comment, #: String?
    :members, #: Array[Member]
    :sources #: Array[String]
  )

  # Returns the class and module scopes declared in the generated RBS of target.
  #: (Target target, String out_root) -> Array[Scope]
  def self.scopes(target, out_root)
    scopes = {}
    sig_files(target, out_root).each do |path|
      source = File.read(path)[/Generated from (\S+)/, 1]
      collect(parse(path), "", scopes, source)
    end
    scopes.values
  end

  # Walks RBS declarations, adding classes, modules, methods, attributes and constants to scopes.
  #: (Array[untyped] decls, String prefix, Hash[String, Scope] scopes, String source) -> void
  def self.collect(decls, prefix, scopes, source)
    decls.each do |decl|
      case decl
      when RBS::AST::Declarations::Class, RBS::AST::Declarations::Module
        name = prefix.empty? ? decl.name.to_s.delete_prefix("::") : "#{prefix}::#{decl.name.to_s.delete_prefix("::")}"
        scope = (scopes[name] ||= Scope.new(name, nil, nil, [], []))
        scope.super_class ||= decl.respond_to?(:super_class) ? decl.super_class&.name&.to_s&.delete_prefix("::") : nil
        scope.comment ||= decl.comment&.string
        scope.sources |= [source]
        visibility = :public
        decl.members.each do |m|
          case m
          when RBS::AST::Members::Public then visibility = :public
          when RBS::AST::Members::Private then visibility = :private
          when RBS::AST::Members::MethodDefinition
            scope.members << Member.new(m.kind == :instance ? :def : :sdef, m.name.to_s,
                                        m.overloads.map { |o| o.method_type.to_s }, m.comment&.string,
                                        m.visibility || visibility, source)
          when RBS::AST::Members::AttrReader, RBS::AST::Members::AttrWriter, RBS::AST::Members::AttrAccessor
            scope.members << Member.new(:attr, m.name.to_s, [m.type.to_s], m.comment&.string,
                                        m.visibility || visibility, source)
          end
        end
        collect(decl.members.grep(RBS::AST::Declarations::Base), name, scopes, source)
      when RBS::AST::Declarations::Constant
        owner = (scopes[prefix] ||= Scope.new(prefix, nil, nil, [], []))
        owner.members << Member.new(:const, decl.name.to_s.split("::").last, [decl.type.to_s], decl.comment&.string, :public, source)
      end
    end
  end

  # Returns the prose of an RBS comment without signature and @rbs lines.
  #: (String? comment) -> String
  def self.description(comment)
    return "" unless comment
    comment.lines.map(&:chomp).reject { |l| l.start_with?(": ") || l.start_with?("@rbs") }.join("\n").strip
  end

  # Returns true when the comment carries a `#:` signature line.
  #: (String? comment) -> bool
  def self.annotated?(comment)
    comment.to_s.lines.any? { |l| l.start_with?(": ") }
  end

  # Returns one message per class or method without a description, without a signature, or attribute without a type.
  #: (Array[Scope] scopes) -> Array[String]
  def self.problems(scopes)
    out = []
    scopes.each do |scope|
      where = scope.sources.first
      out << "#{where}: #{scope.name} has no description" if description(scope.comment).empty? && !scope.name.empty?
      scope.members.each do |m|
        label = "#{scope.name}#{m.kind == :sdef ? '.' : '#'}#{m.name}"
        case m.kind
        when :def, :sdef
          next if m.kind == :sdef && m.name == "new" && m.comment.nil?
          out << "#{m.source}: #{label} has no description" if description(m.comment).empty?
          out << "#{m.source}: #{label} has no `#:` signature" unless annotated?(m.comment)
        when :attr
          out << "#{m.source}: attr #{label} has no trailing `#: Type`" if m.signatures.first == "untyped"
        end
      end
    end
    out
  end

  # Renders scopes as Markdown: constants, attributes and public methods with their signatures.
  #: (Array[Scope] scopes, ?heading: String, ?level: Integer) -> String
  def self.render(scopes, heading: "API", level: 2)
    h = "#" * level
    out = +"#{h} #{heading}\n"
    scopes.each do |scope|
      visible = scope.members.select { |m| m.visibility == :public || m.name == "initialize" }
      next if visible.empty? && scope.comment.nil?
      title = scope.name.empty? ? "(top level)" : scope.name
      title = "#{title} < #{scope.super_class}" if scope.super_class
      out << "\n#{h}# `#{title}`\n"
      text = description(scope.comment)
      out << "\n#{text}\n" unless text.empty?
      out << "\nSource: #{scope.sources.map { |f| "`#{f}`" }.join(', ')}\n"
      consts = visible.select { |m| m.kind == :const }
      unless consts.empty?
        out << "\n#{h}## Constants\n\n"
        consts.each do |m|
          text = description(m.comment).tr("\n", " ")
          out << "- `#{m.name}`: `#{m.signatures.first}`#{text.empty? ? '' : " — #{text}"}\n"
        end
      end
      attrs = visible.select { |m| m.kind == :attr }
      unless attrs.empty?
        out << "\n#{h}## Attributes\n\n"
        attrs.each do |m|
          text = description(m.comment).tr("\n", " ")
          out << "- `#{m.name}`: `#{m.signatures.first}`#{text.empty? ? '' : " — #{text}"}\n"
        end
      end
      defs = visible.select { |m| m.kind == :def || m.kind == :sdef }
      next if defs.empty?
      out << "\n#{h}## Methods\n"
      defs.each do |m|
        prefix = m.kind == :sdef ? "self." : ""
        out << "\n#{h}### `#{prefix}#{m.name}`\n\n"
        out << "```rbs\ndef #{prefix}#{m.name}: #{m.signatures.join("\n  | ")}\n```\n"
        text = description(m.comment)
        out << "\n#{text}\n" unless text.empty?
      end
    end
    out
  end

  # Replaces the generated block of readme with block, or appends it.
  #: (String readme, String block) -> String
  def self.splice(readme, block)
    wrapped = "#{BEGIN_MARK}\n#{block.rstrip}\n#{END_MARK}\n"
    if readme.include?(BEGIN_MARK) && readme.include?(END_MARK)
      readme.sub(/#{Regexp.escape(BEGIN_MARK)}.*?#{Regexp.escape(END_MARK)}\n?/m) { wrapped }
    else
      "#{readme.rstrip}\n\n#{wrapped}"
    end
  end

  # Returns the first prose line of the target's README, or an empty string.
  #: (Target target) -> String
  def self.summary(target)
    path = File.join(ROOT, target.readme)
    return "" unless File.file?(path)
    File.read(path).lines.drop(1).map(&:strip).find { |l| !l.empty? && !l.start_with?("#") } || ""
  end

  # Returns the Markdown files to write, keyed by path relative to the repository root.
  #: (String out_root) -> Hash[String, String]
  def self.documents(out_root)
    docs = {}
    index = +"# API reference\n\nGenerated by `rake docs` from the `#:` signatures and comments in the source.\n\n## mrbgems\n\n"
    areas = +"\n## Host and tooling code\n\n"
    targets.each do |t|
      next if sources(t).empty?
      scopes = scopes(t, out_root)
      if t.readme
        path = File.join(ROOT, t.readme)
        docs[t.readme] = splice(File.file?(path) ? File.read(path) : "# #{t.name}\n", render(scopes))
        index << "- [#{t.name}](../../mrbgems/#{t.name}/README.md) — #{summary(t)}\n"
      else
        docs[t.doc] = "# #{t.name}\n\nGenerated by `rake docs` from `#{t.glob}`.\n\n#{render(scopes)}"
        areas << "- [#{t.name}](#{t.name}.md) — `#{t.glob}`\n"
      end
    end
    docs["docs/api/README.md"] = index + areas
    docs
  end

  # Regenerates the RBS and writes every Markdown document.
  #: () -> void
  def self.generate
    targets.each { |t| generate_sig(t, ROOT) }
    documents(ROOT).each do |rel, text|
      path = File.join(ROOT, rel)
      FileUtils.mkdir_p(File.dirname(path))
      File.write(path, text)
      puts "wrote #{rel}"
    end
  end

  # Aborts listing the problems and out-of-date generated files; prints "docs: ok" otherwise. ONLY limits the list to matching entries.
  #: () -> void
  def self.check
    problems = []
    Dir.mktmpdir("api-docs") do |tmp|
      targets.each { |t| generate_sig(t, tmp) }
      targets.each do |t|
        problems << "#{t.readme} is missing" if t.readme && !File.file?(File.join(ROOT, t.readme))
        problems.concat(self.problems(scopes(t, tmp)))
        fresh = sig_files(t, tmp).to_h { |p| [p.delete_prefix("#{tmp}/"), File.read(p)] }
        current = Dir[File.join(ROOT, t.sig_dir, "**/*.rbs")].to_h { |p| [p.delete_prefix("#{ROOT}/"), File.read(p)] }
        problems << "#{t.sig_dir} is out of date; run `rake docs`" unless fresh == current
      end
      documents(tmp).each do |rel, text|
        path = File.join(ROOT, rel)
        problems << "#{rel} is out of date; run `rake docs`" unless File.file?(path) && File.read(path) == text
      end
    end
    problems = problems.select { |p| p.include?(ENV["ONLY"]) } if ENV["ONLY"]
    abort "docs: #{problems.size} problem(s)\n#{problems.map { |p| "  #{p}" }.join("\n")}\nFix the source comments, then run `rake docs`." unless problems.empty?
    puts "docs: ok"
  end
end

ApiDocs.public_send(ARGV.fetch(0)) if $PROGRAM_NAME == __FILE__
